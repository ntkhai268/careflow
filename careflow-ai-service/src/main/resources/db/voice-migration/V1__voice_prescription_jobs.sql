CREATE TABLE voice_prescription_jobs (
    id UUID PRIMARY KEY,
    consultation_id UUID NOT NULL,
    actor_id UUID NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    transcript_revision INTEGER NOT NULL DEFAULT 1,
    state VARCHAR(20) NOT NULL CHECK (state IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED','EXPIRED')),
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    input_json TEXT,
    result_json TEXT,
    error_code VARCHAR(80),
    correlation_id VARCHAR(36) NOT NULL,
    lease_owner UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(actor_id,idempotency_key)
);
CREATE INDEX voice_job_pending ON voice_prescription_jobs(state,expires_at);
CREATE TABLE voice_prescription_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id UUID NOT NULL,
    actor_id UUID NOT NULL,
    action VARCHAR(40) NOT NULL,
    version BIGINT NOT NULL,
    correlation_id VARCHAR(36) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    schema_version VARCHAR(80) NOT NULL,
    catalog_version VARCHAR(64),
    model_info_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX voice_audit_job ON voice_prescription_audit(job_id,id);
